    }

    /**
     * Arama terimini Türkçe karakterlere ve büyük/küçük harfe duyarsız hale getirir
     */
    fun normalize(text: String): String {
        return text.trim()
            .lowercase(Locale("tr", "TR"))
            .replace('ı', 'i')
            .replace('ğ', 'g')
            .replace('ü', 'u')
            .replace('ş', 's')
            .replace('ö', 'o')
            .replace('ç', 'c')
    }

    /**
     * İl veya ilçe adına göre canlı, hızlı ve akıllı arama yapar.
     * Kullanıcı "kazan", "kahramankazan", "ankara kazan" gibi farklı varyasyonlar yazdığında da bulur.
     */
    fun search(query: String): List<TurkeyDistrict> {
        val normQuery = normalize(query)
        if (normQuery.isBlank()) return emptyList()

        val queryWords = normQuery.split(" ", ",", "-", "/").filter { it.isNotBlank() }
        if (queryWords.isEmpty()) return emptyList()

        return allDistricts.filter { item ->
            val normDistrict = normalize(item.district)
            val normProvince = normalize(item.province)
            val normCombined = "$normProvince $normDistrict"

            // Tüm arama kelimeleri hedefte geçmeli
            queryWords.all { word ->
                normDistrict.contains(word) || normProvince.contains(word) || normCombined.contains(word)
            }
        }.sortedWith { a, b ->
            val aDist = normalize(a.district)
            val bDist = normalize(b.district)
            val aExact = aDist == normQuery
            val bExact = bDist == normQuery
            val aStarts = aDist.startsWith(normQuery)
            val bStarts = bDist.startsWith(normQuery)
            when {
                aExact && !bExact -> -1
                !aExact && bExact -> 1
                aStarts && !bStarts -> -1
                !aStarts && bStarts -> 1
                else -> CollatorTurkish.compare(a.displayName, b.displayName)
            }
        }.take(30)
    }

    /**
     * Belirli bir ilin tüm ilçelerini getirir
     */
    fun getDistricts(province: String): List<TurkeyDistrict> {
        return districtsByProvince[province]
            ?: allDistricts.filter { normalize(it.province) == normalize(province) }
    }
